const originals = new WeakMap();
const originalAttributes = new WeakMap();

function translatedText(node, dictionary) {
  const current = node.nodeValue;
  const saved = originals.get(node);
  const source = saved && current === saved.output ? saved.source : current;
  const trimmed = source.trim();
  if (!trimmed) return;
  const translated = dictionary[trimmed];
  const output = translated ? source.replace(trimmed, translated) : source;
  originals.set(node, { source, output });
  if (node.nodeValue !== output) node.nodeValue = output;
}

function translatedAttribute(el, name, original, dictionary) {
  if (original === null) return;
  const value = dictionary[original] || original;
  if (el.getAttribute(name) !== value) el.setAttribute(name, value);
}

export function translateDom(lang) {
  const dictionary = words[lang] || {};
  document.documentElement.lang = lang === "te" ? "te-IN" : lang === "hi" ? "hi-IN" : "en";
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) translatedText(node, dictionary);

  document.querySelectorAll("input, textarea, button, [aria-label], [title]").forEach(el => {
    if (!originalAttributes.has(el)) {
      originalAttributes.set(el, {
        placeholder: el.getAttribute("placeholder"),
        aria: el.getAttribute("aria-label"),
        title: el.getAttribute("title"),
        value: el.tagName === "INPUT" && !["submit", "button", "hidden"].includes(el.type) ? el.value : null
      });
    }
    const attrs = originalAttributes.get(el);
    translatedAttribute(el, "placeholder", attrs.placeholder, dictionary);
    translatedAttribute(el, "aria-label", attrs.aria, dictionary);
    translatedAttribute(el, "title", attrs.title, dictionary);
    if (attrs.value !== null && dictionary[attrs.value] && el.value === attrs.value) el.value = dictionary[attrs.value];
  });
}

export function getTranslationCoverage(lang) {
  return Object.keys(words[lang] || {}).length;
}
